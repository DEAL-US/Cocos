"""Labels and hierarchy of the terms Cocos reuses from other ontologies (EDAM, ARO, NCBITaxon...).

`fetch_terms` looks every reused term up in the EBI Ontology Lookup Service (OLS), fails if one
does not exist or is obsolete, and returns its label and its ancestors up to the root. The
result is stored in terms.ttl, so the application and the tests never need the internet.
"""
from functools import lru_cache
from pathlib import Path
from urllib.parse import quote

import requests
from rdflib import Graph, Literal, URIRef
from rdflib.namespace import DCTERMS, OWL, RDF, RDFS, XSD

from ..namespaces import EDAM, OBO, bind_prefixes

TERMS_FILE = Path(__file__).resolve().parents[1] / 'vocab' / 'terms.ttl'
OLS_API = 'https://www.ebi.ac.uk/ols4/api'

# OBO prefix (as in obo:ARO_0000073) -> OLS ontology id.
OBO_ONTOLOGIES = {'ARO': 'aro', 'NCBITaxon': 'ncbitaxon', 'NCIT': 'ncit', 'IAO': 'iao'}

# Ontology IRI and license of each source; terms.ttl copies their labels.
SOURCES = {
    'edam': ('http://edamontology.org', 'https://creativecommons.org/licenses/by-sa/4.0/'),
    'aro': ('http://purl.obolibrary.org/obo/aro.owl', 'https://creativecommons.org/licenses/by/4.0/'),
    'ncbitaxon': ('http://purl.obolibrary.org/obo/ncbitaxon.owl', 'https://creativecommons.org/publicdomain/zero/1.0/'),
    'ncit': ('http://purl.obolibrary.org/obo/ncit.owl', 'https://creativecommons.org/licenses/by/4.0/'),
    'iao': ('http://purl.obolibrary.org/obo/iao.owl', 'https://creativecommons.org/licenses/by/4.0/'),
}

HEADER = """# Labels and hierarchy of the ontology terms Cocos reuses, copied from their sources.
# Generated by `python manage.py fetch_terms`; do not edit by hand.
# The labels belong to their ontologies (see each owl:Ontology below for its version and license).
# EDAM is CC BY-SA 4.0, so this file is distributed under CC BY-SA 4.0.

"""


class TermError(Exception):
    """A reused term does not exist or is obsolete."""


@lru_cache(maxsize=1)
def terms_graph():
    """The contents of terms.ttl (empty if it does not exist yet). Treat it as read-only."""
    return Graph().parse(TERMS_FILE, format='turtle') if TERMS_FILE.exists() else Graph()


def ontology_of(iri):
    """Return the OLS id of the ontology that defines `iri`, or None if it is not a reused term."""
    iri = str(iri)
    if iri.startswith(str(EDAM)):
        return 'edam'
    if iri.startswith(str(OBO)):
        prefix = iri[len(str(OBO)):].split('_', 1)[0]
        return OBO_ONTOLOGIES.get(prefix)
    return None


def reused_terms(graph):
    """IRIs in `graph` that come from the reused ontologies."""
    nodes = set(graph.subjects()) | set(graph.predicates()) | set(graph.objects())
    return {node for node in nodes if isinstance(node, URIRef) and ontology_of(node)}


def fetch_terms(iris, get=requests.get):
    """Return a graph with the label and ancestors of every term in `iris`. Raise TermError on any problem."""
    graph = bind_prefixes(Graph())
    pending, seen, ontologies, errors = list(iris), set(), set(), []
    while pending:
        iri = URIRef(pending.pop())
        if iri in seen:
            continue
        seen.add(iri)
        ontology = ontology_of(iri)
        term, kind = _lookup(get, ontology, iri)
        if term is None:
            errors.append(f'{iri} not found in {ontology}')
            continue
        if term.get('is_obsolete'):
            errors.append(f'{iri} ({term.get("label")}) is obsolete in {ontology}')
            continue
        ontologies.add(ontology)
        graph.add((iri, RDFS.label, Literal(term['label'])))
        subclass = RDFS.subPropertyOf if kind == 'properties' else RDFS.subClassOf
        for parent in _parents(get, ontology, kind, iri):
            graph.add((iri, subclass, parent))
            pending.append(parent)
    if errors:
        raise TermError('\n'.join(sorted(errors)))
    for ontology in sorted(ontologies):
        _describe_source(graph, get, ontology)
    return graph


def write_terms(graph, path=TERMS_FILE):
    path.write_text(HEADER + graph.serialize(format='turtle'), encoding='utf-8')


def _term_url(ontology, kind, iri):
    return f'{OLS_API}/ontologies/{ontology}/{kind}/{quote(quote(str(iri), safe=""), safe="")}'


def _lookup(get, ontology, iri):
    for kind in ('terms', 'properties'):
        response = get(_term_url(ontology, kind, iri), timeout=30)
        if response.status_code == 200:
            return response.json(), kind
    return None, None


def _parents(get, ontology, kind, iri):
    response = get(_term_url(ontology, kind, iri) + '/parents', params={'size': 100}, timeout=30)
    if response.status_code != 200:
        return []
    items = response.json().get('_embedded', {}).get(kind, [])
    # OLS also lists Thing and the parents of other ontologies imported by this one.
    return [URIRef(item['iri']) for item in items if ontology_of(item['iri']) == ontology]


def _describe_source(graph, get, ontology):
    ontology_iri, license_url = SOURCES[ontology]
    node = URIRef(ontology_iri)
    graph.add((node, RDF.type, OWL.Ontology))
    graph.add((node, DCTERMS.license, URIRef(license_url)))
    response = get(f'{OLS_API}/ontologies/{ontology}', timeout=30)
    if response.status_code != 200:
        return
    data = response.json()
    version = (data.get('config') or {}).get('version') or data.get('version')
    if version:
        graph.add((node, OWL.versionInfo, Literal(version)))
    # Some ontologies (ARO) publish no version: the date OLS loaded them identifies the snapshot.
    if data.get('loaded'):
        graph.add((node, DCTERMS.date, Literal(data['loaded'][:10], datatype=XSD.date)))
